const EN: Record<string, string> = {};
const ZH: Record<string, string> = {};
for (const [id, en, zh] of ROWS) {
  EN[id] = en;
  ZH[id] = zh;
}

/** Replace `{name}`-style placeholders once. */
export function formatTpl(s: string, vars: Record<string, string | number>): string {
  let o = s;
  for (const [k, v] of Object.entries(vars)) {
    o = o.split(`{${k}}`).join(String(v));
  }
  return o;
}

export function translate(locale: UiLocale, id: string, vars?: Record<string, string | number>): string {
  const raw = (locale === "zh" ? ZH[id] : EN[id]) ?? EN[id] ?? id;
  return vars ? formatTpl(raw, vars) : raw;
}
